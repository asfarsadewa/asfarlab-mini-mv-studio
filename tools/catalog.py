# Builds the catalog of reusable models and motion clips, so that a new film can reuse them before it makes new ones.
# It groups copies of one model by their Tripo request, and copies of one clip by their bytes.
# It writes docs/CATALOG.md and docs/media/catalog_models.png. Look lines come from tools/catalog_looks.json.
# Usage: python tools/catalog.py
import glob, hashlib, json, os, subprocess, sys
from collections import defaultdict
from pathlib import Path
from PIL import Image, ImageDraw

sys.stdout.reconfigure(encoding="utf-8")
ROOT = Path(__file__).resolve().parent.parent
os.chdir(ROOT)
LOOKS = json.loads(Path("tools/catalog_looks.json").read_text(encoding="utf-8"))


def added(path):
    """The time git first saw a path. A path that git does not track yet counts as the newest."""
    out = subprocess.run(["git", "log", "--diff-filter=A", "--format=%at", "--reverse", "--", path], capture_output=True, text=True).stdout.split()
    return int(out[0]) if out else 10 ** 12


def md5(path):
    return hashlib.md5(Path(path).read_bytes()).hexdigest()


# Models: one group per Tripo request. The home is the oldest folder that holds the concept prompt.
groups = defaultdict(list)
for glb in sorted(glob.glob("mvs/*/*/hero.glb")):
    d = Path(glb).parent.as_posix()
    meta = json.loads(Path(d, "hero.json").read_text()) if Path(d, "hero.json").exists() else {}
    groups[meta.get("request") or md5(glb)].append(d)
models = []
for folders in groups.values():
    folders.sort(key=lambda d: (not Path(d, "concept.prompt.txt").exists(), added(d + "/hero.glb"), d))
    home = folders[0]
    outfit = {}
    for d in folders:
        if Path(d, "outfit.json").exists():
            outfit.update(json.loads(Path(d, "outfit.json").read_text()))
    models.append({"home": home, "copies": folders[1:], "rigged": all(Path(d, "hero.blend").exists() for d in folders),
                   "outfit": sorted(outfit), "look": LOOKS.get(home, "")})
models.sort(key=lambda m: m["home"])
missing = [m["home"] for m in models if not m["look"]]

# Motion clips: one group per file content. Several names can share one clip.
clips = defaultdict(lambda: {"names": set(), "paths": []})
for glb in sorted(glob.glob("mvs/*/*/motions/*.glb")):
    c = clips[md5(glb)]
    c["names"].add(Path(glb).stem)
    c["paths"].append(Path(glb).as_posix())
motions = sorted(clips.values(), key=lambda c: sorted(c["names"])[0])

# Contact sheet: the concept of each model, numbered as in the table. A studio with no models yet gets no sheet.
S, cols = 150, 10
rows = max((len(models) + cols - 1) // cols, 1)
sheet = Image.new("RGB", (cols * S, rows * (S + 14)), (240, 235, 225))
draw = ImageDraw.Draw(sheet)
for k, m in enumerate(models):
    im = Image.open(Path(m["home"], "concept.png")).convert("RGB")
    im.thumbnail((S, S))
    x, y = (k % cols) * S, (k // cols) * (S + 14)
    sheet.paste(im, (x + (S - im.width) // 2, y))
    draw.text((x + 3, y + S), f"{k + 1}  {m['home'][4:]}", fill=(0, 0, 0))
Path("docs/media").mkdir(parents=True, exist_ok=True)
if models:
    sheet.save("docs/media/catalog_models.png", optimize=True)

lines = [
    "# Catalog of models and motion clips",
    "",
    "Read this catalog before you paint a concept, build a model or generate a motion. Reuse a model or a clip when it fits the film.",
    "",
    "`tools/catalog.py` builds this file. Run it again after each approved film. Do not edit this file by hand. Add the look line of each new model to `tools/catalog_looks.json`.",
    "",
    "## Reuse a model",
    "",
    "1. Find the model in the table and on the contact sheet.",
    "2. Copy `concept.png`, `hero.blend`, `hero.glb` and `hero.json` from its home folder into the new film. Copy `outfit.json` too if the model has one.",
    "3. Write a new `jobs.json` for the new film. Do not copy the sprites.",
    "4. Run the sprite proof on the new plates before the bake.",
    "",
    "A model that the table marks as not rigged needs `hero.py rig` first.",
    "",
    "![Models](media/catalog_models.png)" if models else "No model has a `hero.glb` yet.",
    "",
    f"## Models ({len(models)})",
    "",
    "| # | Look | Home | Copies | Rigged | Outfit keys |",
    "|---|---|---|---|---|---|",
]
for k, m in enumerate(models):
    copies = ", ".join(f"`{d[4:]}`" for d in m["copies"]) or "None"
    lines.append(f"| {k + 1} | {m['look'] or 'No look line'} | `{m['home']}` | {copies} | {'Yes' if m['rigged'] else 'No'} | {', '.join(m['outfit']) or 'None'} |")
lines += [
    "",
    "## Reuse a motion clip",
    "",
    "A clip lives at `mvs/<film>/<cast>/motions/<clip>.glb` in each film that the table names. The cast folder can be `hero` or another cast member. Copy the clip into `hero/motions/` of the new film. Bake it on the new cast.",
    "",
    "A clip with several names is one file under each name.",
    "",
    f"## Motion clips ({len(motions)})",
    "",
    "| Clip | Films |",
    "|---|---|",
]
for c in motions:
    names = " = ".join(f"`{n}`" for n in sorted(c["names"]))
    films = ", ".join(sorted({p.split("/")[1] for p in c["paths"]}))
    lines.append(f"| {names} | {films} |")
Path("docs/CATALOG.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Wrote docs/CATALOG.md: {len(models)} models, {len(motions)} motion clips.")
if missing:
    print("These models have no look line in tools/catalog_looks.json:", ", ".join(missing))
